#!/usr/bin/env node
// Builds the TapDeploy-installable release: a single-Worker ZIP whose bundle serves the
// frontend from embedded bytes, plus the unit wrangler.jsonc TapDeploy deploys.
//
// Why embedded: TapDeploy rejects Workers Static Assets (`assets.directory`), so the release
// cannot rely on the ASSETS binding. The repo code is untouched: `npm run deploy` and
// `wrangler dev` keep using Static Assets, which take precedence at runtime; only this
// bundle wraps the Worker with an env.ASSETS shim backed by the embedded files.
// Normal deploys never import the generated modules below.
//
//   node scripts/build-tapdeploy-zip.mjs
//   -> dist/releases/pocketchest-tapdeploy.zip { wrangler.jsonc, worker.mjs }
//
// Layout mirrors the CWI single-Worker release (ZIP root = unit dir, ESM main, final values only).
import { execFileSync, spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, extname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseJsonc } from './deploy-preflight-core.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const STAGE = join(root, '.temp', 'tapdeploy');
const RELEASE_DIR = join(STAGE, 'release');
const DIST = join(root, 'dist', 'app');
const OUT_ZIP = join(root, 'dist', 'releases', 'pocketchest-tapdeploy.zip');

const TEXT_TYPES = new Map([
	['.html', 'text/html;charset=UTF-8'],
	['.css', 'text/css;charset=UTF-8'],
	['.js', 'text/javascript;charset=UTF-8'],
	['.mjs', 'text/javascript;charset=UTF-8'],
	['.json', 'application/json'],
	['.txt', 'text/plain;charset=UTF-8'],
	['.svg', 'image/svg+xml'],
	['.webmanifest', 'application/manifest+json'],
]);
const BINARY_TYPES = new Map([
	['.png', 'image/png'],
	['.ico', 'image/x-icon'],
	['.woff2', 'font/woff2'],
	['.wasm', 'application/wasm'],
]);

const SECURITY_HEADERS = {
	'X-Frame-Options': 'DENY',
	'X-Content-Type-Options': 'nosniff',
	'Referrer-Policy': 'strict-origin-when-cross-origin',
	'Content-Security-Policy-Report-Only':
		"default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data: blob:; connect-src 'self'; object-src 'none'; base-uri 'none'; form-action 'self'; frame-ancestors 'none'",
};

const run = (command, args, options = {}) => execFileSync(command, args, { stdio: 'inherit', cwd: root, ...options });

function walk(dir) {
	return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
		const path = join(dir, entry.name);
		return entry.isDirectory() ? walk(path) : [path];
	});
}

function main() {
	run('npm', ['run', 'build']);
	rmSync(STAGE, { recursive: true, force: true });
	mkdirSync(RELEASE_DIR, { recursive: true });
	mkdirSync(join(root, 'dist', 'releases'), { recursive: true });

	// 1. Frontend files become an embedded map: text stays text, binary becomes base64.
	const distFiles = walk(DIST)
		.filter((path) => !path.endsWith('.zip') && !path.endsWith('config.json'))
		.sort();
	if (distFiles.length === 0) throw new Error('dist/app/ holds no frontend files to embed');
	const entries = distFiles.flatMap((path) => {
		// Web paths are relative to the served root (dist/app/); packaging leftovers never ship.
		const webPath = `/${relative(DIST, path).split(sep).join('/')}`;
		// _headers is consumed by Workers Static Assets, never served: the equivalent headers
		// are baked into the entry wrapper below, so the file itself stays out of the bundle.
		if (webPath === '/_headers') return [];
		const ext = extname(path).toLowerCase();
		if (TEXT_TYPES.has(ext)) {
			return [
				[
					webPath,
					{ type: TEXT_TYPES.get(ext), body: readFileSync(path, 'utf8'), binary: false, immutable: webPath.startsWith('/assets/') },
				],
			];
		}
		if (BINARY_TYPES.has(ext)) {
			return [
				[
					webPath,
					{
						type: BINARY_TYPES.get(ext),
						body: readFileSync(path).toString('base64'),
						binary: true,
						immutable: webPath.startsWith('/assets/'),
					},
				],
			];
		}
		throw new Error(`no content type for dist file ${webPath}; extend TEXT_TYPES/BINARY_TYPES first`);
	});
	const dataModule = `// Generated by scripts/build-tapdeploy-zip.mjs. Do not edit.\nexport interface EmbeddedAsset { type: string; body: string; binary: boolean; immutable: boolean }\nexport const embeddedAssets: Record<string, EmbeddedAsset> = ${JSON.stringify(Object.fromEntries(entries))};\n`;
	writeFileSync(join(STAGE, 'embedded-assets.ts'), dataModule);

	// 2. Entry wrapper: the real Worker runs unchanged, with env.ASSETS satisfied by the embedded map.
	const workerEntry = join(root, 'src', 'worker', 'index.ts');
	const entryModule = `// Generated by scripts/build-tapdeploy-zip.mjs. Do not edit.
import worker from ${JSON.stringify(workerEntry)};
import { embeddedAssets } from './embedded-assets.js';

const SECURITY_HEADERS: Record<string, string> = ${JSON.stringify(SECURITY_HEADERS, null, '\t')};

function assetResponse(request: Request): Response | null {
	const path = new URL(request.url).pathname;
	const direct = embeddedAssets[path];
	const pick =
		direct ??
		(path === '/' ? embeddedAssets['/index.html'] : null) ??
		(!path.endsWith('/') && !(path.split('/').pop() ?? '').includes('.') ? embeddedAssets[\`\${path}/index.html\`] : null) ??
		(path.endsWith('/') ? embeddedAssets[\`\${path}index.html\`] : null);
	if (!pick) return null;
	const body = pick.binary
		? Uint8Array.from(atob(pick.body), (c) => c.charCodeAt(0))
		: new TextEncoder().encode(pick.body);
	const headers: Record<string, string> = { 'Content-Type': pick.type, ...SECURITY_HEADERS };
	headers['Cache-Control'] = pick.immutable ? 'public, max-age=31536000, immutable' : 'public, max-age=0, must-revalidate';
	if (request.method === 'HEAD') return new Response(null, { headers });
	return new Response(body as BodyInit, { headers });
}

function notFound(): Response {
	const page = embeddedAssets['/404.html'];
	const headers = { 'Content-Type': 'text/html;charset=UTF-8', ...SECURITY_HEADERS, 'Cache-Control': 'public, max-age=0, must-revalidate' };
	if (page && !page.binary) return new Response(page.body, { status: 404, headers });
	return new Response('Not found', { status: 404, headers });
}

const app = worker as unknown as {
	fetch: (request: Request, env: Record<string, unknown>, ctx: unknown) => Promise<Response>;
	scheduled?: (controller: unknown, env: Record<string, unknown>, ctx: unknown) => Promise<void>;
};

export default {
	fetch(request: Request, env: Record<string, unknown>, ctx: unknown): Promise<Response> {
		return app.fetch(request, { ...env, ASSETS: { fetch: (req: Request) => assetResponse(req) ?? notFound() } }, ctx);
	},
	...(typeof app.scheduled === 'function' ? { scheduled: (c: unknown, e: Record<string, unknown>, x: unknown) => (app.scheduled as Function)(c, e, x) } : {}),
};
`;
	writeFileSync(join(STAGE, 'entry.ts'), entryModule);

	// 3. Bundle with the project's own rolldown (the same toolchain vite uses, no new dependency).
	const bundled = join(STAGE, 'worker.mjs');
	const bundledStatus = spawnSync(
		'npx',
		['rolldown', join(STAGE, 'entry.ts'), '--format', 'esm', '--platform', 'browser', '--file', bundled],
		{ cwd: root, stdio: 'inherit', shell: process.platform === 'win32' },
	);
	if (bundledStatus.status !== 0) throw new Error('rolldown bundling failed');
	const bundleText = readFileSync(bundled, 'utf8');
	if (!/export\s*\{[^}]*\bas\s+default\b/.test(bundleText) || !bundleText.includes('ASSETS') || !bundleText.includes('/index.html')) {
		throw new Error('bundle looks wrong: expected the Worker entry, the ASSETS shim and the embedded pages');
	}

	// 4. Unit wrangler.jsonc: final effective values, only families TapDeploy supports.
	// No `assets` (rejected), no `vars` (inputs own every variable), no placeholders.
	const repo = parseJsonc(readFileSync(join(root, 'wrangler.jsonc'), 'utf8'));
	const r2 = (repo.r2_buckets ?? []).find((item) => item.binding === 'R2_STORAGE');
	if (!r2?.bucket_name) throw new Error('repo wrangler.jsonc needs an R2_STORAGE bucket to suggest');
	const unit = {
		name: repo.name,
		main: 'worker.mjs',
		compatibility_date: repo.compatibility_date,
		r2_buckets: [{ binding: 'R2_STORAGE', bucket_name: r2.bucket_name }],
		...(repo.ratelimits ? { ratelimits: repo.ratelimits } : {}),
		...(repo.triggers ? { triggers: repo.triggers } : {}),
	};
	if (typeof unit.compatibility_date !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(unit.compatibility_date)) {
		throw new Error('repo wrangler.jsonc needs a YYYY-MM-DD compatibility_date to carry over');
	}
	writeFileSync(join(RELEASE_DIR, 'wrangler.jsonc'), `${JSON.stringify(unit, null, '\t')}\n`);
	writeFileSync(join(RELEASE_DIR, 'worker.mjs'), bundleText);

	// 5. Deterministic ZIP: fixed mtimes/permissions, sorted entries, like package.sh.
	for (const file of walk(RELEASE_DIR)) {
		execFileSync('touch', ['-h', '-d', '2020-01-01T00:00:00Z', file], { stdio: 'pipe' });
		execFileSync('chmod', ['644', file], { stdio: 'pipe' });
	}
	const tmpZip = join(STAGE, 'bundle.zip');
	execFileSync('zip', ['-X', '-9', '-q', '-r', tmpZip, 'wrangler.jsonc', 'worker.mjs'], { cwd: RELEASE_DIR, stdio: 'pipe' });
	const staged = new Set(walk(RELEASE_DIR).map((path) => relative(RELEASE_DIR, path).split(sep).join('/')));
	const zipped = new Set(execFileSync('zipinfo', ['-1', tmpZip], { encoding: 'utf8' }).trim().split('\n'));
	if (staged.size !== zipped.size || [...staged].some((name) => !zipped.has(name))) {
		throw new Error(`zip holds [${[...zipped]}] but staged [${[...staged]}]`);
	}
	rmSync(OUT_ZIP, { force: true });
	execFileSync('mv', [tmpZip, OUT_ZIP]);
	const sha = createHash('sha256').update(readFileSync(OUT_ZIP)).digest('hex');
	console.log(JSON.stringify({ archive: 'dist/releases/pocketchest-tapdeploy.zip', files: staged.size, archiveSha256: sha }));
}

try {
	main();
} catch (error) {
	console.error(`[tapdeploy-zip] ${error instanceof Error ? error.message : String(error)}`);
	process.exit(1);
}
